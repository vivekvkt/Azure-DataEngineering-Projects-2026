SELECT
    C.CLAIM_ID,

    C.POLICY_ID,
    C.CUSTOMER_ID,
    P.AGENT_ID,

    C.CLAIM_DATE,
    C.INCIDENT_DATE,
    C.PROCESSED_DATE,

    C.CLAIM_AMOUNT,
    C.APPROVED_AMOUNT,

    C.CLAIM_STATUS,

    C.FRAUD_FLAG AS IS_FRAUDULENT,

    DATEDIFF(
        DAY,
        C.INCIDENT_DATE,
        C.PROCESSED_DATE
    ) AS PROCESSING_TIME_DAYS,

    CURRENT_TIMESTAMP() AS LOADED_AT

FROM {{ source('bronze', 'claims') }} C

LEFT JOIN {{ source('bronze', 'policies') }} P
    ON C.POLICY_ID = P.POLICY_ID
