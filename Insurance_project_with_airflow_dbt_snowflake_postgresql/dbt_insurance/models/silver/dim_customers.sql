SELECT
    CUSTOMER_ID,

    CONCAT(FIRST_NAME, ' ', LAST_NAME) AS FULL_NAME,

    EMAIL,
    PHONE,

    DATE_OF_BIRTH,
    GENDER,
    CITY,
    STATE,
    ZIP_CODE,

    CREATED_AT::DATE AS REGISTRATION_DATE,

    DATEDIFF(
        YEAR,
        DATE_OF_BIRTH,
        CURRENT_DATE()
    ) AS AGE,

    CURRENT_TIMESTAMP() AS LOADED_AT

FROM {{ source('bronze', 'customers') }}
