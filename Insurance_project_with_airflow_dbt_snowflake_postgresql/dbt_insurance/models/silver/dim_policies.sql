SELECT
    POLICY_ID,
    CUSTOMER_ID,
    AGENT_ID,
    POLICY_NUMBER,
    POLICY_TYPE,

    COVERAGE_AMOUNT,
    PREMIUM_AMOUNT,

    START_DATE,
    END_DATE,

    POLICY_STATUS AS STATUS,

    CASE
        WHEN END_DATE >= CURRENT_DATE()
             AND POLICY_STATUS = 'ACTIVE'
        THEN TRUE
        ELSE FALSE
    END AS IS_ACTIVE,

    CURRENT_TIMESTAMP() AS LOADED_AT

FROM {{ source('bronze', 'policies') }}
